/**
 * Imports LinkedIn "Recommendations Received.csv" (from LinkedIn's official
 * data export) and writes src/data/recommendations.js.
 *
 * Usage:
 *   1. LinkedIn → Settings & Privacy → Data privacy → Get a copy of your data
 *   2. Place the file at: data-import/linkedin/Recommendations Received.csv
 *   3. Run: npm run import:recommendations
 */

const fs = require("fs")
const path = require("path")

const CSV_PATH = path.join(
  __dirname,
  "..",
  "data-import",
  "linkedin",
  "Recommendations Received.csv"
)
const OUTPUT_PATH = path.join(__dirname, "..", "src", "data", "recommendations.js")

const parseCsv = text => {
  const rows = []
  let row = []
  let field = ""
  let inQuotes = false

  for (let i = 0; i < text.length; i++) {
    const ch = text[i]
    const next = text[i + 1]

    if (inQuotes) {
      if (ch === '"' && next === '"') {
        field += '"'
        i++
      } else if (ch === '"') {
        inQuotes = false
      } else {
        field += ch
      }
      continue
    }

    if (ch === '"') {
      inQuotes = true
    } else if (ch === ",") {
      row.push(field)
      field = ""
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && next === "\n") i++
      row.push(field)
      field = ""
      if (row.length > 1 || row[0] !== "") rows.push(row)
      row = []
    } else {
      field += ch
    }
  }
  if (field !== "" || row.length > 0) {
    row.push(field)
    rows.push(row)
  }
  return rows
}

// LinkedIn exports dates like "12/02/20, 04:46 PM" → "2020-12-02"
const formatDate = raw => {
  const m = raw.trim().match(/^(\d{1,2})\/(\d{1,2})\/(\d{2,4})/)
  if (!m) return raw.trim()
  const year = m[3].length === 2 ? `20${m[3]}` : m[3]
  return `${year}-${m[1].padStart(2, "0")}-${m[2].padStart(2, "0")}`
}

// LinkedIn wraps recommendation text in <p> tags and HTML entities
const cleanText = raw =>
  raw
    .replace(/<[^>]+>/g, " ")
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, "&")
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/\s+/g, " ")
    .trim()

const slugify = text =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "")

const main = () => {
  if (!fs.existsSync(CSV_PATH)) {
    console.error(`CSV not found: ${CSV_PATH}`)
    console.error(
      "Export your data from LinkedIn (Settings → Data privacy → Get a copy of your data) and place 'Recommendations Received.csv' there."
    )
    process.exit(1)
  }

  const rows = parseCsv(fs.readFileSync(CSV_PATH, "utf8"))
  const header = rows.shift().map(h => h.trim())
  const col = (...names) =>
    header.findIndex(h => names.includes(h.toLowerCase()))

  const idx = {
    firstName: col("first name"),
    lastName: col("last name"),
    company: col("company"),
    jobTitle: col("job title"),
    text: col("text"),
    createdOn: col("creation date", "created on"),
    status: col("status"),
  }

  const recommendations = rows
    .filter(
      r => (r[idx.status] || "").trim().toUpperCase() !== "HIDDEN"
    )
    .map(r => {
      const name = [r[idx.firstName], r[idx.lastName]]
        .filter(Boolean)
        .map(s => s.trim())
        .join(" ")
      const date = formatDate(r[idx.createdOn] || "")
      return {
        slug: `${slugify(name)}-${slugify(date)}`,
        name,
        jobTitle: (r[idx.jobTitle] || "").trim(),
        company: (r[idx.company] || "").trim(),
        text: cleanText(r[idx.text] || ""),
        date,
      }
    })
    .filter(r => r.name && r.text)

  const output = `// Generated by scripts/import-linkedin-recommendations.js — do not edit by hand.
// Re-run \`npm run import:recommendations\` after re-exporting your LinkedIn data.

const recommendations = ${JSON.stringify(recommendations, null, 2)}

export default recommendations
`

  fs.writeFileSync(OUTPUT_PATH, output)
  console.log(
    `Wrote ${recommendations.length} recommendation(s) to ${OUTPUT_PATH}`
  )
}

main()
